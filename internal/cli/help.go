const agentGuide = `# ElevenLabs CLI agent guide

Use elevenlabs --help and each command's --help to discover the current interface.
Output is JSON by default. Use --format pretty for people and --error-format json
for structured errors. Diagnostics go to stderr. No command retries generation.

## Authentication

Ask the owner to sign into ElevenLabs in their browser. Run
"elevenlabs auth export-script" to obtain the export script for that tab.
Import the downloaded private JSON with "elevenlabs auth login --session FILE".
Use --session - to read it through stdin. Never print the file, pass tokens in
arguments, or commit credentials. The export includes the browser user agent.

"auth status" is local. "doctor" renews the session and checks account access.
"profile use NAME" selects an imported profile. --profile overrides that choice.
Galleton owns token refresh and its encrypted vault; local profiles store only
a session reference. Commands start and lease the engine automatically; it stops
after ten idle seconds. No OS startup service is installed. Source installs need
Go once to prepare the pinned engine. Use "auth status --check" for a live check.

## Discover before generating

Read "me subscription", "model list", and "voice list". Use stock or already
owned voices. Generate only when the user has authorized credit consumption.
Use short test inputs. Do not buy credits, upgrade, or clone voices implicitly.

"speech generate --text-file FILE --voice ID --output FILE" produces MP3 audio.
"dialogue generate --input FILE --output FILE" accepts a JSON array whose entries
have text and voice_id. --output - writes only binary audio to stdout.
Existing output files are never overwritten. A failed download removes the new
partial file. Partial audio sent to stdout cannot be recalled.

"history list --search TEXT" finds generated entries; "history show ID" inspects
one; "history download ID --output FILE" downloads it. Listing returns one page
with continuation metadata; no automatic pagination is performed.

"sound generate --text-file FILE" returns the generation JSON. Explore sharing
must already be disabled in the account. The CLI will not silently publish or
change that setting. "sound download ID --output FILE" downloads an Opus result.

## Errors and limits

Exit codes: 0 success, 1 local/network failure, 2 usage, 3 authentication,
4 permission/plan/connection restriction, 5 rate limit, 6 API response error,
130 interrupted. On detected_unusual_activity, stop generation and report the
service restriction. A valid login does not prove generation access.

Browser captures establish request shapes; they do not prove every CLI request
works on every account or network. Studio, music, transcription uploads, dubbing,
voice cloning and agent execution are not exposed as supported commands.
Do not fabricate commands or claim support because a feature exists on the site.
`

func (a *app) skills() *cobra.Command {
	parent := &cobra.Command{Use: "skills", Short: "Read embedded instructions for agents"}
	parent.AddCommand(
		&cobra.Command{Use: "list", Short: "List embedded agent guides", Args: exact(0), RunE: func(_ *cobra.Command, _ []string) error {
			return a.print([]any{map[string]string{"name": "elevenlabs", "description": "Authentication, generation, downloads and service limits"}})
		}},
		&cobra.Command{Use: "get NAME", Short: "Print an agent guide as Markdown", Args: exact(1), RunE: func(_ *cobra.Command, args []string) error {
			if args[0] != "elevenlabs" {
				return usage("unknown guide; use skills list")
			}
			_, err := fmt.Fprint(a.stdout, agentGuide)
			return err
		}},
	)
	return parent
}

// CommandReference uses the same command tree as the installed CLI, without
// executing commands or loading credentials. Its output is deterministic for CI.
func CommandReference() string {
	a := &app{stdin: strings.NewReader(""), stdout: io.Discard, stderr: io.Discard}
	root := a.root("dev")
	root.InitDefaultHelpCmd()
	root.InitDefaultCompletionCmd()
	var out strings.Builder
	out.WriteString("# Command reference\n\nGenerated by `make docs` from the Cobra command tree. Do not edit by hand.\n\n")
	var render func(*cobra.Command)
	render = func(cmd *cobra.Command) {
		if cmd.Hidden || cmd.Name() == "help" {
			return
		}
		cmd.InitDefaultHelpFlag()
		fmt.Fprintf(&out, "## %s\n\n%s\n\n```text\n%s\n```\n\n", cmd.CommandPath(), cmd.Short, cmd.UseLine())
		if flags := cmd.LocalFlags().FlagUsages(); flags != "" {
			fmt.Fprintf(&out, "Local flags:\n\n```text\n%s```\n\n", flags)
		}
		if flags := cmd.InheritedFlags().FlagUsages(); flags != "" {
			fmt.Fprintf(&out, "Global flags:\n\n```text\n%s```\n\n", flags)
		}
		for _, child := range cmd.Commands() {
			render(child)
		}
	}
	render(root)
	return out.String()
}
